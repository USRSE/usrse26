/* ==========================================================================
   USRSE'26 abstract pages
   Enhances the markup generated by scripts/build-program.js
   (pages/program/abstracts/*.md).

   The disclosure toggle itself is native <details>/<summary> behavior — no
   script involved, so the page still works with JavaScript off. This file
   only adds the three things <details> cannot do on its own:

     1. open the entry a schedule deep link points at,
     2. drive the expand / collapse-all control,
     3. open every entry for printing, and put them back afterward.

   Dependency-free on purpose: the site's jQuery/Bootstrap bundle loads
   after this script and has nothing to offer it.
   ========================================================================== */

(function () {
  'use strict';

  var root = document.querySelector('.abstracts');
  if (!root) return;

  var panels = root.querySelectorAll('details.abstract');

  // ------------------------------------------------------------------
  // 1. Deep links from the program schedule
  // ------------------------------------------------------------------

  // Arriving from the schedule is a cross-document navigation, so the
  // browser has already done its own fragment scroll by the time this
  // runs. Opening the target doesn't move it — the abstract expands below
  // the summary row — so the scroll here is to re-settle the position and
  // let the entry's scroll-margin-top clear the fixed navbar. Static
  // entries have nothing to open and fall through to the same scroll.
  function reveal() {
    var id = decodeURIComponent(location.hash.slice(1));
    if (!id) return;
    var el = document.getElementById(id);
    // Guards against a fragment that matches something else on the page.
    if (!el || !root.contains(el)) return;
    if (el.tagName === 'DETAILS') el.open = true;
    el.scrollIntoView();
  }

  reveal();
  // A second link to the same page changes the fragment without reloading.
  window.addEventListener('hashchange', reveal);

  // ------------------------------------------------------------------
  // 2. Expand all / Collapse all
  // ------------------------------------------------------------------

  var toolbar = root.querySelector('.abstracts__toolbar');
  var toggleAll = root.querySelector('.abstracts__toggle-all');

  if (toolbar && toggleAll && panels.length) {
    // The generator renders the toolbar hidden, so it never appears on a
    // page where this script didn't run.
    toolbar.hidden = false;

    var allOpen = function () {
      return Array.prototype.every.call(panels, function (p) { return p.open; });
    };

    // The button's label is its state — a screen reader announces it on
    // focus. No aria-expanded: that describes a button controlling one
    // region, and this one controls every panel on the page.
    var relabel = function () {
      toggleAll.textContent = allOpen() ? 'Collapse all' : 'Expand all';
    };

    toggleAll.addEventListener('click', function () {
      var open = !allOpen();
      Array.prototype.forEach.call(panels, function (p) { p.open = open; });
      relabel();
    });

    // Individual toggling must not leave the label lying about the page.
    Array.prototype.forEach.call(panels, function (p) {
      p.addEventListener('toggle', relabel);
    });

    relabel();
  }

  // ------------------------------------------------------------------
  // 3. Printing
  // ------------------------------------------------------------------

  // A printed program must carry every abstract, and reading it must not
  // cost the reader their place: record what was open, open everything,
  // then put it back. The stylesheet's @media print rule is a fallback for
  // print paths that never fire these events, not the mechanism.
  var beforePrint = [];

  window.addEventListener('beforeprint', function () {
    beforePrint = Array.prototype.map.call(panels, function (p) { return p.open; });
    Array.prototype.forEach.call(panels, function (p) { p.open = true; });
  });

  window.addEventListener('afterprint', function () {
    // Some engines fire afterprint on their own; with nothing recorded
    // there is no state to restore, and guessing would collapse the page.
    if (!beforePrint.length) return;
    Array.prototype.forEach.call(panels, function (p, i) {
      p.open = beforePrint[i];
    });
    beforePrint = [];
  });
})();
